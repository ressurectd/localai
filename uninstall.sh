#!/bin/sh
# Uninstall localai on Linux (and other Unix-like systems).
#
# Removes the virtual environment, the launchers install.sh created in ~/.local/bin,
# and build caches.
#
# Your data is NOT removed unless you explicitly ask. Conversations, usage history,
# audit logs, backups and configuration are yours; this script tells you where they
# are and what they contain, then asks.
#
# Ollama, your downloaded models and your Trash are never touched by this script.
#
# Usage:
#   ./uninstall.sh [--remove-data] [--yes]
#
#   --remove-data  Also delete conversations, usage history, audit logs and
#                  configuration. You will still be asked to type DELETE.
#   --yes          Skip confirmation prompts. Combined with --remove-data this
#                  deletes data without asking; use it only in automation you control.
#
# POSIX sh on purpose: it runs under dash, busybox and bash alike.

set -eu

REMOVE_DATA=0
ASSUME_YES=0

usage() {
    sed -n '2,/^# POSIX sh/p' "$0" | sed -e 's/^# \{0,1\}//' -e '$d'
}

while [ $# -gt 0 ]; do
    case "$1" in
        --remove-data) REMOVE_DATA=1 ;;
        -y | --yes) ASSUME_YES=1 ;;
        -h | --help) usage; exit 0 ;;
        *) echo "uninstall.sh: unknown option '$1' (try --help)" >&2; exit 2 ;;
    esac
    shift
done

ROOT=$(cd "$(dirname "$0")" && pwd -P)
VENV="$ROOT/.venv"
VENV_PY="$VENV/bin/python"
USER_BIN="$HOME/.local/bin"
MARKER="# localai-launcher: generated by install.sh"

if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
    C_CYAN=$(printf '\033[36m'); C_GREEN=$(printf '\033[32m')
    C_YELLOW=$(printf '\033[33m'); C_DIM=$(printf '\033[2m'); C_OFF=$(printf '\033[0m')
else
    C_CYAN=''; C_GREEN=''; C_YELLOW=''; C_DIM=''; C_OFF=''
fi
step() { printf '\n%s==> %s%s\n' "$C_CYAN" "$1" "$C_OFF"; }
ok()   { printf '  %s[ok]%s %s\n' "$C_GREEN" "$C_OFF" "$1"; }
warn() { printf '  %s[!]%s  %s\n' "$C_YELLOW" "$C_OFF" "$1"; }
dim()  { printf '    %s%s%s\n' "$C_DIM" "$1" "$C_OFF"; }

# Mirrors localai.config.paths.default_home(). A launcher with --portable set is the
# only record of portable mode, so the localai-data folder's presence decides it.
data_directory() {
    if [ -n "${LOCALAI_HOME:-}" ]; then echo "$LOCALAI_HOME"; return; fi
    if [ -d "$ROOT/localai-data" ]; then echo "$ROOT/localai-data"; return; fi
    case "${XDG_DATA_HOME:-}" in
        /*) echo "$XDG_DATA_HOME/localai" ;;
        *) echo "$HOME/.local/share/localai" ;;
    esac
}

# Names of launchers in ~/.local/bin that carry our marker. Anything else is left
# alone. Names, not paths: $HOME may contain spaces, and these lists are word-split.
our_launchers() {
    for name in ai localai; do
        if [ -f "$USER_BIN/$name" ] && grep -qF "$MARKER" "$USER_BIN/$name" 2>/dev/null; then
            echo "$name"
        fi
    done
}

printf '%slocalai uninstaller%s\n-------------------\n' "$C_CYAN" "$C_OFF"

DATA_DIR=$(data_directory)
LAUNCHERS=$(our_launchers)

# --- Report what exists before removing anything ------------------------------
step 'What will be removed'

echo '  Program files:'
if [ -d "$VENV" ]; then echo "    $VENV"; else dim "$VENV (not present)"; fi
if [ -n "$LAUNCHERS" ]; then
    for name in $LAUNCHERS; do echo "    $USER_BIN/$name"; done
else
    dim "launchers in $USER_BIN (none created by install.sh)"
fi

echo
echo "  Your data:  $DATA_DIR"
if [ -d "$DATA_DIR" ]; then
    COUNT='unknown'
    DB="$DATA_DIR/data/localai.db"
    if [ -f "$DB" ] && [ -x "$VENV_PY" ]; then
        COUNT=$("$VENV_PY" - "$DB" <<'PY' 2>/dev/null || echo unknown
import sqlite3, sys
try:
    # Read-only URI: counting must never modify, or create, the database.
    c = sqlite3.connect(f"file:{sys.argv[1]}?mode=ro", uri=True)
    print(c.execute("SELECT COUNT(*) FROM conversations").fetchone()[0])
except Exception:
    print("unknown")
PY
)
    fi
    SIZE=$(du -sh "$DATA_DIR" 2>/dev/null | cut -f1)
    echo "    $COUNT saved conversation(s), ${SIZE:-?} total"
    echo '    includes: configuration, usage history, audit log, file backups'
else
    dim '(no data directory found)'
fi

printf '\n  %sNOT touched by this script:%s\n' "$C_GREEN" "$C_OFF"
echo '    Ollama itself'
echo '    Your downloaded models (ollama list)'
echo '    Your Trash, including anything localai deleted'
echo '    Any file localai read or wrote in your own folders'

# --- Confirm ------------------------------------------------------------------
if [ "$ASSUME_YES" != 1 ]; then
    if [ ! -t 0 ]; then
        echo
        echo 'Not running interactively; re-run with --yes to uninstall. Nothing was changed.'
        exit 1
    fi
    printf '\nRemove the localai program files? [y/N] '
    read -r answer || answer=''
    case "$answer" in
        [Yy]*) ;;
        *) printf '%sCancelled. Nothing was changed.%s\n' "$C_YELLOW" "$C_OFF"; exit 0 ;;
    esac
fi

# --- Remove program files -----------------------------------------------------
step 'Removing program files'

if [ -d "$VENV" ]; then rm -rf "$VENV"; ok "Removed $VENV"; fi
for name in $LAUNCHERS; do
    rm -f "$USER_BIN/$name"
    ok "Removed $USER_BIN/$name"
done
for cache in .pytest_cache .mypy_cache .ruff_cache build dist; do
    if [ -e "$ROOT/$cache" ]; then rm -rf "${ROOT:?}/$cache"; ok "Removed $cache"; fi
done
# bin/ is part of the source tree, so it stays; without .venv its launchers just
# report that the environment is missing.

# --- Data ---------------------------------------------------------------------
if [ -d "$DATA_DIR" ]; then
    step 'Your data'
    DELETE_DATA=$REMOVE_DATA
    if [ "$REMOVE_DATA" = 1 ] && [ "$ASSUME_YES" != 1 ]; then
        warn 'This permanently deletes your conversations, usage history and audit log.'
        printf '  Type DELETE to confirm removing %s: ' "$DATA_DIR"
        read -r confirm || confirm=''
        if [ "$confirm" != DELETE ]; then
            DELETE_DATA=0
            printf '  %sNot confirmed; data kept.%s\n' "$C_YELLOW" "$C_OFF"
        fi
    fi

    if [ "$DELETE_DATA" = 1 ]; then
        rm -rf "${DATA_DIR:?}"
        ok "Deleted $DATA_DIR"
    else
        printf '  %sKept: %s%s\n' "$C_GREEN" "$DATA_DIR" "$C_OFF"
        echo '  Delete it yourself at any time, or re-run with --remove-data.'
    fi
fi

printf '\n%sUninstall complete.%s\n' "$C_GREEN" "$C_OFF"
echo 'The source folder itself was left in place; delete it if you no longer want it.'
