#!/bin/sh
# Install localai on Linux (and other Unix-like systems): a local-first agentic
# terminal UI for Ollama models.
#
# Checks prerequisites, creates an isolated virtual environment in this folder,
# installs the package, and verifies the result by running the built-in diagnostics.
#
# Nothing is installed system-wide, nothing needs root, and no service is registered.
# Everything lives in this folder, plus a state directory under
# $XDG_DATA_HOME/localai (normally ~/.local/share/localai) and, if you agree, two
# small launcher scripts in ~/.local/bin.
#
# Usage:
#   ./install.sh [--with-extractors] [--portable] [--no-path-update] [--yes]
#
#   --with-extractors  Also install the optional document extractors (PDF, Word,
#                      Excel, PowerPoint, RTF, HTML). Adds roughly 40 MB.
#   --portable         Keep all state next to the installation (localai-data/)
#                      rather than under ~/.local/share. Suitable for a USB stick.
#   --no-path-update   Do not create launchers in ~/.local/bin.
#   --yes              Answer yes to every question (for unattended installs).
#
# POSIX sh on purpose: it runs under dash, busybox and bash alike.

set -eu

# --- Arguments ----------------------------------------------------------------
PORTABLE=0
WITH_EXTRACTORS=0
PATH_UPDATE=1
ASSUME_YES=0

usage() {
    sed -n '2,/^# POSIX sh/p' "$0" | sed -e 's/^# \{0,1\}//' -e '$d'
}

while [ $# -gt 0 ]; do
    case "$1" in
        --portable) PORTABLE=1 ;;
        --with-extractors) WITH_EXTRACTORS=1 ;;
        --no-path-update) PATH_UPDATE=0 ;;
        -y | --yes) ASSUME_YES=1 ;;
        -h | --help) usage; exit 0 ;;
        *) echo "install.sh: unknown option '$1' (try --help)" >&2; exit 2 ;;
    esac
    shift
done

ROOT=$(cd "$(dirname "$0")" && pwd -P)
VENV="$ROOT/.venv"
VENV_PY="$VENV/bin/python"
BIN_DIR="$ROOT/bin"
USER_BIN="$HOME/.local/bin"
# Written into every launcher we create in ~/.local/bin, so the uninstaller and a
# re-install can tell our files from someone else's command of the same name.
MARKER="# localai-launcher: generated by install.sh"

# --- Output helpers -----------------------------------------------------------
if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
    C_CYAN=$(printf '\033[36m'); C_GREEN=$(printf '\033[32m')
    C_YELLOW=$(printf '\033[33m'); C_RED=$(printf '\033[31m'); C_OFF=$(printf '\033[0m')
else
    C_CYAN=''; C_GREEN=''; C_YELLOW=''; C_RED=''; C_OFF=''
fi
step() { printf '\n%s==> %s%s\n' "$C_CYAN" "$1" "$C_OFF"; }
ok()   { printf '  %s[ok]%s %s\n' "$C_GREEN" "$C_OFF" "$1"; }
warn() { printf '  %s[!]%s  %s\n' "$C_YELLOW" "$C_OFF" "$1"; }
err()  { printf '  %s[x]%s  %s\n' "$C_RED" "$C_OFF" "$1" >&2; }
note() { printf '       %s\n' "$1"; }

# ask "question" default(Y|N) -> 0 for yes. Non-interactive runs take the default.
ask() {
    if [ "$ASSUME_YES" = 1 ]; then return 0; fi
    if [ ! -t 0 ]; then [ "$2" = Y ]; return; fi
    if [ "$2" = Y ]; then hint='[Y/n]'; else hint='[y/N]'; fi
    printf '  %s %s ' "$1" "$hint"
    read -r answer || answer=''
    case "$answer" in
        '') [ "$2" = Y ] ;;
        [Yy]*) return 0 ;;
        *) return 1 ;;
    esac
}

printf '%s' "$C_CYAN"
cat <<'BANNER'
+------------------------------------------------------------+
|  localai - local-first AI terminal for Ollama               |
|  No cloud account. No telemetry. Your files stay here.      |
+------------------------------------------------------------+
BANNER
printf '%s' "$C_OFF"

if [ "$(id -u)" = 0 ]; then
    warn 'Running as root. localai does not need root; a normal user account is safer,'
    note 'because the model'"'"'s tools run with the permissions of the user who starts it.'
fi

# --- 1. Python ----------------------------------------------------------------
step 'Checking Python'

PYTHON=''
for candidate in python3.13 python3.12 python3.11 python3 python; do
    exe=$(command -v "$candidate" 2>/dev/null) || continue
    if "$exe" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)' 2>/dev/null; then
        PYTHON=$exe
        ok "$("$exe" --version 2>&1)  ($exe)"
        break
    else
        warn "$("$exe" --version 2>&1) at $exe is too old (need 3.11+)"
    fi
done

if [ -z "$PYTHON" ]; then
    err 'Python 3.11 or newer was not found.'
    echo
    echo '  Install it with your package manager, for example:'
    echo '    sudo apt install python3 python3-venv     # Debian, Ubuntu'
    echo '    sudo dnf install python3                  # Fedora'
    echo '    sudo pacman -S python                     # Arch'
    echo
    echo '  Then re-run this script.'
    exit 1
fi

# Debian and Ubuntu ship venv's pip bootstrap separately; without it `python -m venv`
# fails halfway and leaves a broken environment behind. Check first.
if [ ! -x "$VENV_PY" ] && ! "$PYTHON" -c 'import venv, ensurepip' 2>/dev/null; then
    err "Python's venv module (with ensurepip) is not available."
    version=$("$PYTHON" -c 'import sys; print(f"{sys.version_info[0]}.{sys.version_info[1]}")')
    echo "  On Debian/Ubuntu:  sudo apt install python3-venv  (or python${version}-venv)"
    exit 1
fi

# --- 2. Ollama ----------------------------------------------------------------
step 'Checking Ollama'

# Queried with Python's standard library rather than curl, which is not always
# installed. Loopback only, with a short timeout -- nothing else is contacted.
OLLAMA_STATUS=0
"$PYTHON" - <<'PY' || OLLAMA_STATUS=$?
import json, sys, urllib.request
try:
    with urllib.request.urlopen("http://127.0.0.1:11434/api/tags", timeout=5) as r:
        models = json.load(r).get("models", [])
except Exception:
    sys.exit(3)
print(f"  [ok] Ollama is running with {len(models)} model(s) installed")
for m in models[:5]:
    caps = ",".join(m.get("capabilities") or []) or "chat"
    print(f"       {m.get('name')}  {m.get('size', 0) / 1024**3:.1f} GB  [{caps}]")
sys.exit(0 if models else 4)
PY

case "$OLLAMA_STATUS" in
    0) ;;
    4) warn 'No models installed. Pull one with:  ollama pull qwen3:8b' ;;
    *)
        if command -v ollama >/dev/null 2>&1; then
            warn 'Ollama is installed but not responding on 127.0.0.1:11434'
            note 'Start it with:  ollama serve   (or: systemctl start ollama)'
        else
            warn 'Ollama was not found.'
            note 'Install it from https://ollama.com/download'
        fi
        note 'Installation will continue; localai will report this at startup.'
        ;;
esac

# --- 3. Virtual environment ---------------------------------------------------
step 'Creating the virtual environment'

if [ -x "$VENV_PY" ]; then
    ok 'Virtual environment already exists; reusing it'
else
    if ! "$PYTHON" -m venv "$VENV"; then
        err 'Failed to create the virtual environment'
        rm -rf "$VENV"
        exit 1
    fi
    ok "Created $VENV"
fi

# --- 4. Install ---------------------------------------------------------------
step 'Installing localai and its dependencies'

"$VENV_PY" -m pip install --upgrade pip --quiet || warn 'Could not upgrade pip; continuing'

if [ "$WITH_EXTRACTORS" = 1 ]; then target='.[extract]'; else target='.'; fi
if ! (cd "$ROOT" && "$VENV_PY" -m pip install -e "$target" --quiet); then
    err 'Installation failed (see the pip output above)'
    exit 1
fi
if [ "$WITH_EXTRACTORS" = 1 ]; then
    ok 'Installed localai with document extractors'
else
    ok 'Installed localai'
fi

# --- 5. Launchers -------------------------------------------------------------
step 'Creating the launchers'

mkdir -p "$BIN_DIR"

# Two names for the same thing: `ai` because it is what you actually want to type,
# `localai` because every document and script references it. Both resolve the venv
# relative to their own location, so the folder can be moved without reinstalling.
# Without --portable this is byte-identical to the committed bin/ai.
write_launcher() {
    {
        echo '#!/bin/sh'
        echo '# localai launcher for Git Bash / MSYS.'
        if [ "$PORTABLE" = 1 ]; then echo 'export LOCALAI_PORTABLE=1'; fi
        cat <<'LAUNCHER'
here="$(cd "$(dirname "$0")/.." && pwd)"
py="$here/.venv/Scripts/python.exe"
[ -x "$py" ] || py="$here/.venv/bin/python"
if [ ! -x "$py" ]; then
  echo "localai: virtualenv not found under $here/.venv" >&2
  exit 78
fi
exec "$py" -m localai "$@"
LAUNCHER
    } >"$1"
    chmod 755 "$1"
}

for name in ai localai; do
    write_launcher "$BIN_DIR/$name"
done
ok "Launchers 'ai' and 'localai' written to $BIN_DIR"
if [ "$PORTABLE" = 1 ]; then
    ok 'Portable mode: state will live in localai-data beside this folder'
fi

# --- 6. PATH ------------------------------------------------------------------
# Small wrapper scripts in ~/.local/bin (the XDG location most distributions already
# put on PATH) rather than edits to your shell startup files. A wrapper, not a
# symlink: the launcher finds the venv relative to its own path, which a symlink
# would point at ~/.local instead.
LINKED=''
if [ "$PATH_UPDATE" = 1 ]; then
    step "Adding 'ai' and 'localai' to your PATH"
    echo "  This lets you type 'ai' from any terminal."
    if ask "Create launchers in $USER_BIN?" Y; then
        mkdir -p "$USER_BIN"
        for name in ai localai; do
            dest="$USER_BIN/$name"
            if [ -e "$dest" ] && ! grep -qF "$MARKER" "$dest" 2>/dev/null; then
                # Never replace someone else's command; `ai` is a popular name.
                warn "$dest already exists and is not ours; left untouched"
                note "Use '$BIN_DIR/$name' or the other name instead."
                continue
            fi
            existing=$(command -v "$name" 2>/dev/null || true)
            if [ -n "$existing" ] && [ "$existing" != "$dest" ]; then
                warn "'$name' already resolves to $existing, which may take precedence"
            fi
            quoted=$(printf '%s' "$BIN_DIR/$name" | sed "s/'/'\\\\''/g")
            printf '#!/bin/sh\n%s\nexec '"'"'%s'"'"' "$@"\n' "$MARKER" "$quoted" >"$dest"
            chmod 755 "$dest"
            LINKED="$LINKED $name"
        done
        if [ -n "$LINKED" ]; then
            ok "Created:$LINKED  (in $USER_BIN)"
        fi
        case ":$PATH:" in
            *":$USER_BIN:"*) ;;
            *)
                warn "$USER_BIN is not on your PATH yet."
                note 'Many distributions add it at your next login. Otherwise add this'
                note 'line to ~/.profile (or ~/.bashrc / ~/.zshrc) and open a new terminal:'
                # shellcheck disable=SC2016 # printed literally, for the user to paste
                note '  export PATH="$HOME/.local/bin:$PATH"'
                ;;
        esac
    else
        echo "  Skipped. Run it directly: $BIN_DIR/ai"
    fi
fi

# --- 7. Verify ----------------------------------------------------------------
step 'Verifying the installation'

if [ "$PORTABLE" = 1 ]; then export LOCALAI_PORTABLE=1; fi
"$VENV_PY" -m localai config init >/dev/null 2>&1 || warn 'Could not write a default config file'
DOCTOR_EXIT=0
"$VENV_PY" -m localai doctor || DOCTOR_EXIT=$?

echo
if [ "$DOCTOR_EXIT" = 0 ]; then
    printf '%sInstallation complete.%s\n' "$C_GREEN" "$C_OFF"
else
    printf '%sInstalled, but the diagnostics reported a problem (see above).%s\n' "$C_YELLOW" "$C_OFF"
    printf '%slocalai will still start; fix the reported items when convenient.%s\n' "$C_YELLOW" "$C_OFF"
fi

case " $LINKED " in
    *' ai '*) cmd='ai' ;;
    *' localai '*) cmd='localai' ;;
    *) cmd="$BIN_DIR/ai" ;;
esac
printf '%s' "$C_CYAN"
cat <<EOF

Next steps
  $cmd                          launch the terminal interface
  $cmd doctor                   re-run diagnostics
  $cmd providers scan           see your models and how well each is supported
  $cmd --help                   every command

  'localai' works too - same program, longer name.

First run
  Press F1 for help, Ctrl+P for commands, Ctrl+M to pick a model.
  Permission mode starts at 'auto': reads run freely, changes ask first.
  Deleted files go to your Trash (~/.local/share/Trash) and can be restored.

Docs
  README.md, docs/user-guide.md, docs/installation.md

Uninstall
  ./uninstall.sh              (keeps your conversations unless you say otherwise)
EOF
printf '%s' "$C_OFF"

exit "$DOCTOR_EXIT"
